#!/usr/bin/env node
/**
 * Generates `src/icons/registry.ts`: the kebab-case icon-name -> icon-component
 * map that lets `F0Icon` (and every component taking an `IconType`) accept a
 * plain string instead of an imported component.
 *
 * Names are derived from the component names in the icon barrels:
 *
 *   app/AlertCircleLine  -> "alert-circle-line"
 *   app/Heading1         -> "heading-1"
 *   modules/LMS          -> "modules:lms"
 *   ai/Calendar          -> "ai:calendar"
 *
 * `app` icons are unprefixed because they are the overwhelmingly common case;
 * every other namespace is prefixed, which is what keeps the 35 names that
 * exist in more than one namespace (Calendar, Search, People, ...) addressable.
 *
 * `animated` is deliberately excluded: all of its icons import `motion/react`,
 * and the registry is eagerly bundled, so including them would drag the motion
 * runtime into every consumer of `F0Icon`. Animated icons stay component-only.
 *
 * Usage:
 *   node scripts/generate-icon-registry.mjs           # write the registry
 *   node scripts/generate-icon-registry.mjs --check    # fail if out of date
 */

import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url))
const ICONS_DIR = path.resolve(SCRIPT_DIR, "..", "src", "icons")
const OUTPUT_FILE = path.join(ICONS_DIR, "registry.ts")

/**
 * Namespaces included in the registry, in output order.
 * `prefix: null` means names are exposed bare (no `namespace:` prefix).
 */
const NAMESPACES = [
  { dir: "app", prefix: null, alias: "AppIcons" },
  { dir: "modules", prefix: "modules", alias: "ModuleIcons" },
  { dir: "ai", prefix: "ai", alias: "AiIcons" },
]

/** PascalCase (or SCREAMING) component name -> kebab-case icon name. */
export function toKebabCase(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1-$2")
    .replace(/([A-Za-z])(\d)/g, "$1-$2")
    .toLowerCase()
}

function readComponentNames(dir) {
  return readdirSync(path.join(ICONS_DIR, dir))
    .filter((file) => file.endsWith(".tsx"))
    .map((file) => file.replace(/\.tsx$/, ""))
    .sort()
}

function buildEntries() {
  const entries = []
  const seen = new Map()

  for (const { dir, prefix, alias } of NAMESPACES) {
    for (const component of readComponentNames(dir)) {
      const name = prefix
        ? `${prefix}:${toKebabCase(component)}`
        : toKebabCase(component)

      const previous = seen.get(name)
      if (previous) {
        throw new Error(
          `Duplicate icon name "${name}": generated from both ` +
            `${previous.dir}/${previous.component} and ${dir}/${component}. ` +
            `Rename one of the assets in @factorialco/f0-core.`
        )
      }
      seen.set(name, { dir, component })

      entries.push({ name, namespace: dir, reference: `${alias}.${component}` })
    }
  }

  return entries
}

/** `app` -> `AppIconName`, `modules` -> `ModulesIconName`. */
function nameTypeFor(namespace) {
  return `${namespace[0].toUpperCase()}${namespace.slice(1)}IconName`
}

function render(entries) {
  const imports = NAMESPACES.map(
    ({ dir, alias }) => `import * as ${alias} from "./${dir}"`
  ).join("\n")

  const namespaceSummary = NAMESPACES.map(({ dir, prefix }) =>
    prefix ? `\`${prefix}:\` for \`${dir}\`` : `unprefixed for \`${dir}\``
  ).join(", ")

  // Quote only what has to be quoted, so the output is already oxfmt-clean and
  // `--check` compares like with like.
  const body = entries
    .map(({ name, reference }) => {
      const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : `"${name}"`
      return `  ${key}: ${reference},`
    })
    .join("\n")

  // Per-namespace name unions, so props can be narrowed to a subset of the
  // sets — `IconType<"modules">`, `IconType<"modules" | "ai">`.
  const nameTypes = NAMESPACES.map(({ dir }) => {
    const members = entries
      .filter((entry) => entry.namespace === dir)
      .map(({ name }) => `  | "${name}"`)
      .join("\n")

    return `/** Names of the \`${dir}\` icons. */\nexport type ${nameTypeFor(dir)} =\n${members}\n`
  }).join("\n")

  const namespaceMembers = NAMESPACES.map(
    ({ dir }) => `  ${dir}: ${nameTypeFor(dir)}`
  ).join("\n")

  return `// AUTO-GENERATED by scripts/generate-icon-registry.mjs — do not edit.
// Run \`pnpm generate-icon-registry\` after adding or renaming an icon.
import type { IconComponent } from "./types"

${imports}

${nameTypes}
/**
 * Maps each icon set to the names it contributes. Lets a prop accept only some
 * of the sets, via \`IconType<"modules">\` or \`IconName<"modules" | "ai">\`.
 */
export interface IconNamesByNamespace {
${namespaceMembers}
}

/** The icon sets addressable by name. */
export type IconNamespace = keyof IconNamesByNamespace

/**
 * Name of an icon, optionally narrowed to some of the sets.
 * ${namespaceSummary}.
 */
export type IconName<Namespace extends IconNamespace = IconNamespace> =
  IconNamesByNamespace[Namespace]

/**
 * Every icon addressable by name.
 *
 * \`animated\` icons are intentionally absent — they pull in \`motion/react\`,
 * and this map is eagerly bundled. Pass those as components.
 */
export const iconRegistry = {
${body}
} satisfies Record<IconName, IconComponent>
`
}

const entries = buildEntries()
const output = render(entries)

if (process.argv.includes("--check")) {
  let current = null
  try {
    current = readFileSync(OUTPUT_FILE, "utf8")
  } catch {
    console.error(
      `${path.relative(process.cwd(), OUTPUT_FILE)} is missing. Run \`pnpm generate-icon-registry\`.`
    )
    process.exit(1)
  }

  if (current !== output) {
    console.error(
      `${path.relative(process.cwd(), OUTPUT_FILE)} is out of date. Run \`pnpm generate-icon-registry\`.`
    )
    process.exit(1)
  }

  console.log(`Icon registry is up to date (${entries.length} icons).`)
} else {
  writeFileSync(OUTPUT_FILE, output)
  console.log(
    `Generated ${path.relative(process.cwd(), OUTPUT_FILE)} (${entries.length} icons).`
  )
}
